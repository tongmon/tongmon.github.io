export const GLYPH_H = 5;

export interface Glyph {
  w: number;
  bits: boolean[][];
}

const glyphs = new Map<string, Glyph>();
for (const [ch, src] of Object.entries(SRC)) {
  const rows = src.split("|");
  glyphs.set(ch, { w: rows[0].length, bits: rows.map((r) => [...r].map((c) => c === "#")) });
}

export function glyph(ch: string): Glyph {
  return glyphs.get(ch.toUpperCase()) ?? glyphs.get("?")!;
}

export function textWidth(str: string): number {
  let w = 0;
  for (const ch of str) w += glyph(ch).w + 1;
  return Math.max(0, w - 1);
}
